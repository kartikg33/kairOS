#!/usr/bin/env bash

set -e

export DISPLAY=:99

# ------------------------------------------------------------
# D-Bus
# ------------------------------------------------------------

eval "$(dbus-launch --sh-syntax)"

# ------------------------------------------------------------
# Virtual display
# ------------------------------------------------------------

Xvfb :99 \
    -screen 0 1920x1080x24 \
    -ac \
    +extension GLX \
    +render \
    +composite \
    >/tmp/xvfb.log 2>&1 &

sleep 2

# ------------------------------------------------------------
# XFCE
# ------------------------------------------------------------

startxfce4 >/tmp/xfce.log 2>&1 &

sleep 3

# ------------------------------------------------------------
# OpenClaw
# ------------------------------------------------------------

openclaw gateway run >/tmp/openclaw.log 2>&1 &

# ------------------------------------------------------------
# Element
# ------------------------------------------------------------

element --disable-gpu >/tmp/element.log 2>&1 &

# ------------------------------------------------------------
# VNC
# ------------------------------------------------------------

x11vnc \
    -display :99 \
    -forever \
    -shared \
    -nopw \
    -listen 0.0.0.0 \
    -rfbport 5900 \
    >/tmp/x11vnc.log 2>&1 &

# ------------------------------------------------------------
# noVNC
# ------------------------------------------------------------

/usr/share/novnc/utils/novnc_proxy \
    --vnc localhost:5900 \
    --listen 6080 \
    >/tmp/novnc.log 2>&1 &

echo
echo "=========================================="
echo " kairOS container"
echo "=========================================="
echo
echo "Desktop:  http://localhost:6080/vnc.html"
echo "OpenClaw: http://localhost:18789"
echo

wait